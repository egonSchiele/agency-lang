// Writes every std:: module and its public exported functions into
// lib/stdlib/stdlibModules.data.ts, so `learn` can name the module that
// exports a function without reading the stdlib at run time. `make` runs
// this after the build and rebuilds when the file changed. CI fails when
// the committed file differs from the one `make` writes.
//
// Building the table parses every stdlib module, which takes about 3s, so
// the script skips it when nothing it reads has changed since the last
// run: the stdlib sources, the compiled code that walks their exports, and
// the data file itself. Those hashes are kept in .agency-build/, which
// `make clean` deletes.
//
// It uses the compiled helpers in dist/, so it needs a build first.
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { _stdlibModuleTable } from "../dist/lib/stdlib/agencyFunctions.js";
import {
  computeCompilerStamp,
  computeStdlibHash,
  hashBytes,
} from "../dist/lib/compiler/buildManifest.js";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(packageRoot, "lib", "stdlib", "stdlibModules.data.ts");
const stampFile = path.join(packageRoot, ".agency-build", "stdlib-modules.stamp");
const distLib = path.join(packageRoot, "dist", "lib");

const readOrNull = (file) => {
  try {
    return readFileSync(file, "utf-8");
  } catch {
    return null;
  }
};

const inputsHash = hashBytes(
  computeStdlibHash(path.join(packageRoot, "stdlib")) +
    computeCompilerStamp(distLib, path.join(distLib, "stdlib", "agencyFunctions.js")),
);
const stampFor = (text) => `${inputsHash} ${hashBytes(text ?? "")}`;

const current = readOrNull(target);
if (readOrNull(stampFile) === stampFor(current)) {
  process.exit(0);
}

const text =
  "// Generated by scripts/generate-stdlib-modules.mjs from the stdlib/ folder.\n" +
  "// Do not edit; run `make` after adding, removing, or renaming a stdlib export.\n\n" +
  "export const STDLIB_MODULES: Record<string, string[]> = " +
  JSON.stringify(_stdlibModuleTable(), null, 2) +
  ";\n";

if (current !== text) {
  writeFileSync(target, text);
  console.log(`wrote ${path.relative(packageRoot, target)}`);
}
mkdirSync(path.dirname(stampFile), { recursive: true });
writeFileSync(stampFile, stampFor(text));
