// Writes the built-in effect sets of stdlib/effectSets.agency into
// lib/runtime/effectSets.data.ts, so the runtime does not parse the .agency
// file at run time. `make` runs this after the build and rebuilds when the
// file changed; lib/runtime/effectSets.test.ts fails when it is stale.
//
// It uses the parser in dist/, so it needs a build first.
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { parseEffectSets } from "../dist/lib/runtime/effectSets.js";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(packageRoot, "stdlib", "effectSets.agency");
const target = path.join(packageRoot, "lib", "runtime", "effectSets.data.ts");

const sets = parseEffectSets(readFileSync(source, "utf-8"), source);
const text =
  "// Generated by scripts/generate-effect-sets.mjs from stdlib/effectSets.agency.\n" +
  "// Do not edit; run `make` after changing the .agency file.\n" +
  'import type { EffectSetInfo } from "./effectSets.js";\n\n' +
  "export const BUILTIN_EFFECT_SETS: Record<string, EffectSetInfo> = " +
  JSON.stringify(sets, null, 2) +
  ";\n";

const current = (() => {
  try {
    return readFileSync(target, "utf-8");
  } catch {
    return null;
  }
})();
if (current !== text) {
  writeFileSync(target, text);
  console.log(`wrote ${path.relative(packageRoot, target)}`);
}
