/**
 * The synthesized grading module for discovered agency tests, and its
 * snapshot with a STABLE revision.
 *
 * The generic snapshot identity is `<absolute module path>@<bundle hash>` —
 * useless for a module generated into a per-run staging path (every run a
 * new revision) whose harness files live OUTSIDE the bundle (edits change
 * nothing). So the synthesized snapshot carries an explicit revision: a
 * logical source identity derived from the suite + test id, and a hash
 * folding the harness pair contents in beside the bundle. Both loaders
 * assign `${sourceIdentity}@${sha256}` when it is recorded; its absence
 * takes the legacy code-only identity, so old run directories stay
 * readable.
 */
import * as fs from "fs";
import * as os from "os";
import * as path from "path";
import type { SuiteIdentity } from "@/runDirectory/annotations.js";
import type { AgencyTestDefinition, Test } from "../runTypes.js";
import { parseTestFileSandbox } from "../../testFormat/schema.js";
import { sha256Text } from "@/utils/hash.js";
import { snapshotGradingModule, type GradersSnapshot } from "./gradingModule.js";
import { safeDeleteDirectoryWithin } from "../../utils.js";

export type HarnessPair = {
  harnessAgency: string;
  harnessJson: string;
  name: string;
};

export type SynthesizeGradersModuleArgs = {
  siblingGradersPath?: string;
  pairs: HarnessPair[];
};

export type SynthesizedGradersModule = { moduleSource: string };

/** Deterministic: fixed template, pairs sorted by name, so an unchanged
 *  test directory synthesizes byte-identical source. */
export function synthesizeGradersModule(
  args: SynthesizeGradersModuleArgs,
): SynthesizedGradersModule {
  const pairs = [...args.pairs].sort((a, b) => a.name.localeCompare(b.name));
  const lines: string[] = [
    "// generated by eval agency-test discovery — do not edit",
    'import { AgencyTestGrader } from "agency-lang/eval";',
  ];
  if (args.siblingGradersPath !== undefined) {
    lines.push(`import sibling from ${JSON.stringify(args.siblingGradersPath)};`);
    // importBundle normalizes single-vs-array only at LOAD time; this
    // spread runs before that, so normalize here.
    lines.push("const siblingList = Array.isArray(sibling) ? sibling : [sibling];");
  }
  lines.push("export default [");
  if (args.siblingGradersPath !== undefined) {
    lines.push("  ...siblingList,");
  }
  for (const pair of pairs) {
    lines.push(
      `  new AgencyTestGrader({ harnessAgency: ${JSON.stringify(pair.harnessAgency)}, ` +
        `harnessJson: ${JSON.stringify(pair.harnessJson)}, name: ${JSON.stringify(pair.name)} }),`,
    );
  }
  lines.push("];");
  return { moduleSource: lines.join("\n") + "\n" };
}

/** One canonical serializer for the tagged suite identity: hashed, never
 *  delimiter-concatenated, so separator-like source strings and differing
 *  shas can never collide; inline runs get a distinct tag. */
export function suiteIdentityDigest(suite: SuiteIdentity | undefined): string {
  if (suite === undefined) return "inline";
  return sha256Text(JSON.stringify({ source: suite.source, sha: suite.sha ?? null })).slice(0, 16);
}

export function agencyTestsSourceIdentity(
  suite: SuiteIdentity | undefined,
  testId: string,
): string {
  return `agency-tests:${suiteIdentityDigest(suite)}/${testId}`;
}

/** Preflight + snapshot for one test's discovered harness pairs. Every
 *  refusal here happens before any agent runs. */
export async function snapshotAgencyTestGraders(args: {
  test: Test;
  suite: SuiteIdentity | undefined;
}): Promise<GradersSnapshot> {
  const defs = args.test.agencyTests ?? [];
  const testId = args.test.id ?? "";
  for (const def of defs) {
    validateHarnessPair(def);
  }
  const { moduleSource } = synthesizeGradersModule({
    ...(args.test.graders !== undefined ? { siblingGradersPath: args.test.graders } : {}),
    pairs: defs.map((d) => ({
      harnessAgency: d.harnessAgency,
      harnessJson: d.harnessJson,
      name: d.name,
    })),
  });
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), "agency-tests-graders-"));
  try {
    const modulePath = path.join(staging, "agencyTests.graders.ts");
    fs.writeFileSync(modulePath, moduleSource, "utf-8");
    const snapshot = await snapshotGradingModule(modulePath);
    const bundleCode =
      snapshot.files.find((entry) => entry.name === snapshot.bundleFile)?.content ?? "";
    const revisionInputs = defs
      .flatMap((d) => [d.harnessAgency, d.harnessJson])
      .map((file) => sha256Text(fs.readFileSync(file, "utf-8")))
      .sort();
    const sourceIdentity = agencyTestsSourceIdentity(args.suite, testId);
    return {
      ...snapshot,
      source: sourceIdentity,
      revision: {
        sourceIdentity,
        sha256: sha256Text(bundleCode + revisionInputs.join("")),
      },
    };
  } finally {
    safeDeleteDirectoryWithin(os.tmpdir(), staging);
  }
}

function validateHarnessPair(def: AgencyTestDefinition): void {
  const jsonText = fs.readFileSync(def.harnessJson, "utf-8");
  const parsed = parseTestFileSandbox(jsonText, path.basename(def.harnessJson));
  // Eval-discovered harnesses are sibling pairs by convention; a json
  // declaring a different source would widen the wrapper's authorization.
  if (parsed.sourceFile !== path.basename(def.harnessAgency)) {
    throw new Error(
      `${def.harnessJson} declares sourceFile ${JSON.stringify(parsed.sourceFile)}, but eval ` +
        `discovery requires the sibling harness ${path.basename(def.harnessAgency)}`,
    );
  }
  for (const testCase of parsed.cases) {
    for (const answer of testCase.interrupts) {
      if (answer.action === "approve") {
        throw new Error(
          `${def.harnessJson} (${testCase.nodeName}): eval grading rejects all effects; this ` +
            `scripted approval cannot take effect — remove it or restructure the test`,
        );
      }
    }
  }
}
