// Writes every std:: module and its public exported functions into
// lib/stdlib/stdlibModules.data.ts, so `learn` can name the module that
// exports a function without reading the stdlib at run time. `make` runs
// this after the build and rebuilds when the file changed;
// lib/stdlib/stdlibModules.test.ts fails when it is stale.
//
// It uses the compiled helpers in dist/, so it needs a build first.
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { _stdlibModuleTable } from "../dist/lib/stdlib/agencyFunctions.js";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(packageRoot, "lib", "stdlib", "stdlibModules.data.ts");

const text =
  "// Generated by scripts/generate-stdlib-modules.mjs from the stdlib/ folder.\n" +
  "// Do not edit; run `make` after adding, removing, or renaming a stdlib export.\n\n" +
  "export const STDLIB_MODULES: Record<string, string[]> = " +
  JSON.stringify(_stdlibModuleTable(), null, 2) +
  ";\n";

const current = (() => {
  try {
    return readFileSync(target, "utf-8");
  } catch {
    return null;
  }
})();
if (current !== text) {
  writeFileSync(target, text);
  console.log(`wrote ${path.relative(packageRoot, target)}`);
}
